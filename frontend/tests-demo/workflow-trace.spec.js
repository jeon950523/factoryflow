import { test, expect } from '@playwright/test'

test('order row selection preserves status filter and detail after a browser reload', async ({ page }) => {
  await page.goto('/orders?status=DRAFT')
  const list = page.getByRole('table', { name: '생산지시 목록' })
  await list.getByRole('button', { name: 'WO-DEMO-READY' }).click()
  await expect(page).toHaveURL(/\/orders\?status=DRAFT&id=2$/)
  await expect(page.locator('.detail-panel')).toContainText('WO-DEMO-READY')
  await page.reload()
  await expect(page.getByRole('combobox', { name: '진행 상태' })).toHaveValue('DRAFT')
  await expect(page.locator('.detail-panel')).toContainText('WO-DEMO-READY')
  await expect(page.getByRole('table', { name: '선택 생산지시 소요 원자재' })
    .getByRole('link', { name: '산업용 강판 LOT 재고' }))
    .toHaveAttribute('href', '/inventory?itemType=RAW_MATERIAL&itemId=1')
})

test('BOM → raw LOT → physical movement → production → finished LOT → shipment → movement is consistent', async ({ page }) => {
  await page.goto('/items?itemId=4')
  const bom = page.getByRole('table', { name: '완제품 BOM 구성표' })
  await bom.getByRole('link', { name: '산업용 강판 LOT 재고 확인' }).click()
  await expect(page).toHaveURL(/\/inventory\?itemType=RAW_MATERIAL&itemId=1$/)
  const rawLot = page.getByRole('table', { name: '선택 품목 LOT별 재고' })
    .getByRole('row').filter({ hasText: 'STEEL-A01' })
  await expect(rawLot.getByRole('cell').nth(3)).toHaveText('50')
  await expect(rawLot.getByRole('cell').nth(4)).toHaveText('40')
  await page.getByRole('link', { name: '선택 품목 이동 이력' }).click()
  await expect(page).toHaveURL(/\/movements\?itemId=1$/)
  const moves = page.getByRole('table', { name: '선택 품목 재고 이동 이력' })
  await expect(moves).toContainText('+50')
  await expect(moves).toContainText('−10')

  await moves.getByRole('link', { name: '생산지시 #1 확인' }).click()
  await expect(page).toHaveURL(/\/orders\?id=1$/)
  const order = page.locator('.erp-orders .detail-panel')
  await expect(order).toContainText('WO-DEMO-COMPLETE')
  await expect(order.getByRole('link', { name: '완제품 LOT' })).toHaveAttribute('href',
    '/inventory?itemType=FINISHED_GOOD&itemId=4')
  await order.getByRole('link', { name: '완제품 LOT' }).click()

  await expect(page).toHaveURL(/\/inventory\?itemType=FINISHED_GOOD&itemId=4$/)
  const finishedLot = page.getByRole('table', { name: '선택 품목 LOT별 재고' })
    .getByRole('row').filter({ hasText: 'FG-WO-1' })
  await expect(finishedLot.getByRole('cell').nth(3)).toHaveText('5')
  await expect(finishedLot.getByRole('cell').nth(4)).toHaveText('3')
  await page.getByRole('link', { name: '선택 품목 이동 이력' }).click()
  await expect(page).toHaveURL(/\/movements\?itemId=4$/)
  await expect(moves).toContainText('+5')
  await expect(moves).toContainText('−2')

  await moves.getByRole('link', { name: '완제품 출고 #1 확인' }).click()
  await expect(page).toHaveURL(/\/shipments\?id=1$/)
  const allocations = page.getByRole('table', { name: 'LOT별 출고 배분 내역' })
  await expect(allocations).toContainText('LOT #4')
  await expect(allocations).toContainText('2 EA')
  await page.getByRole('link', { name: '완제품 이동 이력' }).click()
  await expect(page).toHaveURL(/\/movements\?itemId=4$/)
  await page.reload()
  await expect(moves).toContainText('−2')
  await page.getByRole('link', { name: '현재 LOT 재고 보기' }).click()
  await expect(page).toHaveURL(/\/inventory\?itemId=4$/)
  await expect(page.locator('.erp-lot-summary')).toContainText('현재고 3 EA')
})
