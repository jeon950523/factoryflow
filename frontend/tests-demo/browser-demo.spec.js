test('QC confirmation requires an exact safe integer total before accepting the operation', async ({ page }) => {
  await page.goto('/orders')
  await page.getByRole('button', { name: 'WO-DEMO-READY', exact: true }).click()
  const detail = page.locator('.detail-panel')
  await detail.getByRole('button', { name: '자재 예약', exact: true }).click()
  await detail.getByRole('button', { name: '생산 시작', exact: true }).click()
  await detail.getByRole('button', { name: '생산 완료', exact: true }).click()
  const qc = detail.locator('.qc-inline')
  await expect(qc).toBeVisible()
  await qc.getByRole('spinbutton', { name: '합격 수량' }).fill('9')
  await qc.getByRole('spinbutton', { name: '불합격 수량' }).fill('0')
  await expect(detail.getByRole('button', { name: '품질검사 확정', exact: true })).toBeDisabled()
  await expect(qc.getByText('수량 합계 또는 입력값 확인 필요')).toBeVisible()
  await qc.getByRole('spinbutton', { name: '합격 수량' }).fill('8')
  await qc.getByRole('spinbutton', { name: '불합격 수량' }).fill('2')
  await expect(detail.getByRole('button', { name: '품질검사 확정', exact: true })).toBeEnabled()
  await detail.getByRole('button', { name: '품질검사 확정', exact: true }).click()
  await expect(detail).toContainText('완료')
  await expect(detail.getByText('이 생산지시는 더 이상 실행할 작업이 없습니다.')).toBeVisible()
})

test('creating a production order from a filtered list deep-links its detail after reload', async ({ page }) => {
  await page.goto('/orders?status=COMPLETED')
  await expect(page.getByRole('combobox', { name: '진행 상태' })).toHaveValue('COMPLETED')
  await page.getByRole('button', { name: '생산지시 생성' }).click()
  await page.locator('.dialog .item-search-toggle').click()
  await page.locator('.dialog .item-search-option').filter({ hasText: 'FG-CONTROL-100' }).click()
  await page.locator('.dialog input[type="number"]').fill('1')
  await page.locator('.dialog button[type="submit"]').click()
  await expect(page).toHaveURL(/\/orders\?id=3/)
  await expect(page.locator('.detail-panel')).toContainText('WO-DEMO-0003')
  await expect(page.getByRole('combobox', { name: '진행 상태' })).toHaveValue('')
  await page.reload()
  await expect(page.locator('.detail-panel')).toContainText('WO-DEMO-0003')
})
