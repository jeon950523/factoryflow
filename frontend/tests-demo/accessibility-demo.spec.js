import { test, expect } from '@playwright/test'

test('item drawer traps Tab and restores focus after Escape', async ({ page }) => {
  await page.goto('/items')
  const opener = page.getByRole('button', { name: '품목 등록', exact: true })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '품목 등록' })
  const field = dialog.getByPlaceholder('예: RM-SHEET-001')
  await expect(field).toBeFocused()

  const close = dialog.getByRole('button', { name: '닫기' })
  await close.focus()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '품목 등록' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('product picker consumes first Escape; second Escape closes order drawer', async ({ page }) => {
  await page.goto('/orders')
  const opener = page.getByRole('button', { name: '생산지시 생성' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '생산지시 생성' })
  const picker = dialog.locator('.item-search-toggle')
  await expect(picker).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(picker).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(picker).toHaveAttribute('aria-expanded', 'false')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
})

test('inventory and shipment drawers restore their original action focus', async ({ page }) => {
  await page.goto('/inventory')
  const receipt = page.getByRole('button', { name: '원자재 입고', exact: true })
  await receipt.click()
  await expect(page.getByRole('dialog', { name: '원자재 입고' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(receipt).toBeFocused()

  await page.goto('/shipments')
  const shipment = page.getByRole('button', { name: '출고 등록' })
  await shipment.click()
  await expect(page.getByRole('dialog', { name: '완제품 출고 등록' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(shipment).toBeFocused()
})

test('supporting descriptions and audit notes retain readable font sizes', async ({ page }) => {
  await page.goto('/movements?itemId=1')
  const foot = page.locator('.erp-movement-foot')
  await expect(foot).toBeVisible()
  expect(await foot.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(12)

  await page.goto('/items?itemId=4')
  const note = page.locator('.erp-items-note')
  await expect(note).toBeVisible()
  expect(await note.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(12)
  const sub = page.locator('.erp-item-meta small').first()
  expect(await sub.evaluate(el => parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(12)
})
